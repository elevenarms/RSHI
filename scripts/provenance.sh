#!/usr/bin/env bash
# Prints PROVENANCE.md (from committed history only, so it is reproducible):
#   bash scripts/provenance.sh > PROVENANCE.md
# Env: RSHI (repo root, default: this script's parent), SUB (DishwasherBench checkout with the
# rshi branch, default: upstream/DishwasherBench), BASE (upstream base commit, default 99b974a),
# REV (RSHI revision to describe, default HEAD).
set -euo pipefail
RSHI=${RSHI:-$(cd "$(dirname "$0")/.." && pwd)}
SUB=${SUB:-$RSHI/upstream/DishwasherBench}
BASE=$(git -C "$SUB" rev-parse "${BASE:-99b974a}^{commit}")
REV=${REV:-HEAD}
FORK_REV=${FORK_REV:-$(git -C "$RSHI" rev-parse "$REV:upstream/DishwasherBench" 2>/dev/null || git -C "$SUB" rev-parse HEAD)}
EMPTY=$(git -C "$RSHI" hash-object -t tree /dev/null)
FIRST=$(git -C "$RSHI" log --reverse --format=%ad --date=iso "$REV" -- crew studio docs | head -1)

row() { sed -e 's/|/\\|/g'; }

cat <<MD
# SPARKLETEAM provenance

SPARKLETEAM is original hackathon work (repository elevenarms/RSHI) built on DishwasherBench.
Generated by \`scripts/provenance.sh\` from git history (regenerate: \`bash scripts/provenance.sh > PROVENANCE.md\`).

## Upstream base

- Repository: [composo-ai/DishwasherBench](https://github.com/composo-ai/DishwasherBench) (MIT, Composo)
- Base commit: \`$BASE\`
- Base commit date: $(git -C "$SUB" log -1 --format='%ad (committed %cd)' --date=iso "$BASE")
- Base commit subject: $(git -C "$SUB" log -1 --format=%s "$BASE" | row)

Everything in \`upstream/DishwasherBench\` up to and including that commit is upstream's work.

## Hackathon day

- Date: ${FIRST%% *}
- First original commit: $FIRST
- Every commit listed below is after the upstream base commit.

## Our commits in this repository (SPARKLETEAM, elevenarms/RSHI)

Author dates and committer dates are the original ones (history imported with \`git filter-repo\`,
which keeps both).

| Author date | Committer date | Commit | Subject |
|---|---|---|---|
MD
git -C "$RSHI" log --reverse --format='| %ad | %cd | `%h` | %s |' --date=iso "$REV"

cat <<MD

## Our commits on the fork's \`rshi\` branch (elevenarms/DishwasherBench)

Compare: https://github.com/elevenarms/DishwasherBench/compare/main...rshi

| Author date | Committer date | Commit | Subject |
|---|---|---|---|
MD
git -C "$SUB" log --reverse --format='| %ad | %cd | `%h` | %s |' --date=iso "$BASE..$FORK_REV"

cat <<MD

## Original SPARKLETEAM files (ours): \`crew/\`, \`studio/\`, \`docs/\`, repository root

| File | Lines |
|---|---|
MD
git -C "$RSHI" diff --numstat "$EMPTY" "$REV" -- . ':(exclude)upstream' ':(exclude)PROVENANCE.md' ':(exclude)pnpm-lock.yaml' |
  awk -F'\t' '{ printf "| `%s` | %s |\n", $3, ($1 == "-" ? "binary" : $1) }'
echo
echo '`pnpm-lock.yaml` is generated by pnpm.'

cat <<MD

## Upstream files modified on the fork's \`rshi\` branch

\`git diff --numstat $(git -C "$SUB" rev-parse --short "$BASE") $(git -C "$SUB" rev-parse --short "$FORK_REV")\` (added / removed lines). No other upstream file is modified.

| File | Added | Removed |
|---|---|---|
MD
git -C "$SUB" diff --numstat "$BASE" "$FORK_REV" | awk -F'\t' '{ printf "| `%s` | %s | %s |\n", $3, $1, $2 }'
